package com.example.pixellauncher

/**
 * Пресет "Magic OS": замеры с видео (576x1262, ~28.7 к/с), усреднены по пяти открытиям и закрытиям.
 *
 * Открытие. Окно растёт из значка до полного экрана, каждый край независимо приближается к краю экрана
 * по экспоненте с постоянной времени TAU около 108 мс (за 35 мс остаётся 72% пути, за 105 мс 38%,
 * за 245 мс 10%). Поэтому ширина обгоняет высоту: значок лежит выше середины, нижнему краю идти дальше.
 * Значок на заставке окна масштабируется вместе с окном (0.38 от ширины окна).
 *
 * Закрытие. Окно сжимается за ~210 мс не в сам значок, а в "карточку" примерно 2.2 x 2.7 значка:
 * сначала медленно, потом быстрее (таблица Q), высота схлопывается раньше ширины. Затем окно растворяется,
 * и настоящий значок возвращается с лёгким увеличением 1.25 -> 1.0.
 *
 * Домашний экран. Пока окно открыто, он уменьшается до 0.916 (вокруг центра) и размывается.
 * Уменьшение идёт быстро (за ~170 мс), возврат вдвое медленнее (~330 мс).
 */
object MagicSpec {
    const val TAU = 108f
    const val OPEN_MS = 440f
    const val CLOSE_MS = 210f
    const val FADE_END_MS = 245f
    const val SETTLE_MS = 150f
    const val LAUNCH_AT_MS = 100f
    const val ICON_W = 0.38f
    const val START_SCALE = 1.25f
    const val BLUR_SIGMA_W = 0.004f
    const val HOME_IN_MS = 200L
    const val HOME_OUT_MS = 330L

    private val T = floatArrayOf(0f, 35f, 70f, 105f, 140f, 175f, 210f)
    private val Q = floatArrayOf(1f, 0.93f, 0.77f, 0.5f, 0.3f, 0.1f, 0f)

    /** Оставшаяся доля пути при закрытии (1 = окно как было, 0 = карточка у значка). */
    fun closeQ(t: Float): Float {
        if (t <= 0f) return 1f
        for (i in 1 until T.size) {
            if (t <= T[i]) {
                val u = (t - T[i - 1]) / (T[i] - T[i - 1])
                return Q[i - 1] + (Q[i] - Q[i - 1]) * u
            }
        }
        return 0f
    }
}
